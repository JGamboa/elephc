<?php
function preg_quote(string $str, ?string $delimiter = null) {
    $map = [
        "." => "\\.", "\\" => "\\\\", "+" => "\\+", "*" => "\\*", "?" => "\\?",
        "[" => "\\[", "^" => "\\^", "]" => "\\]", "$" => "\\$", "(" => "\\(",
        ")" => "\\)", "{" => "\\{", "}" => "\\}", "=" => "\\=", "!" => "\\!",
        ">" => "\\>", "<" => "\\<", "|" => "\\|", ":" => "\\:", "-" => "\\-",
        "#" => "\\#", "\0" => "\\000",
    ];
    if ($delimiter !== null && $delimiter !== "") {
        $d = substr($delimiter, 0, 1);
        $map[$d] = "\\" . $d;
    }
    return strtr($str, $map);
}
